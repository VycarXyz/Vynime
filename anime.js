const createCard = (anime) => {
  const card = document.createElement("article");
  card.className = "video-card";
  card.tabIndex = 0;
  card.setAttribute("role", "button");
  const hasEpisodes = anime.episodes.some((episode) => episode.title.trim() && episode.source.trim());
  card.setAttribute("aria-label", hasEpisodes ? `Putar ${anime.title}` : `Slot thumbnail ${anime.title}, isi data anime di anime.js`);

  const thumbnail = document.createElement("div");
  thumbnail.className = "thumbnail-wrap";
  const image = document.createElement("img");
  if (anime.poster) image.src = anime.poster;
  else {
    thumbnail.classList.add("is-placeholder");
    const placeholder = document.createElement("span");
    placeholder.textContent = "Isi thumbnail";
    thumbnail.append(placeholder);
  }
  image.alt = "";
  image.loading = "lazy";
  image.decoding = "async";
  thumbnail.append(image);

  if (viewingWatched) {
    const removeButton = document.createElement("button");
    removeButton.className = "watched-remove";
    removeButton.type = "button";
    removeButton.textContent = "×";
    removeButton.setAttribute("aria-label", `Hapus ${anime.title} dari telah ditonton`);
    removeButton.addEventListener("click", (event) => {
      event.stopPropagation();
      watchedVideos.delete(getWatchedKey(anime));
      saveWatchedVideos();
      renderGallery();
    });
    thumbnail.append(removeButton);
  }

  const info = document.createElement("div");
  info.className = "video-info";
  const avatar = document.createElement("span");
  avatar.className = "channel-avatar";
  avatar.setAttribute("aria-hidden", "true");
  avatar.textContent = "✦";
  const copy = document.createElement("div");
  copy.className = "video-copy";
  const title = document.createElement("h2");
  title.className = "video-title";
  title.textContent = anime.title;
  const meta = document.createElement("p");
  meta.className = "video-meta";
  meta.textContent = `${anime.channel || "Anime"} · ${anime.category}`;
  copy.append(title, meta);
  info.append(avatar, copy);
  card.append(thumbnail, info);

  const activate = () => {
    const firstEpisode = anime.episodes.find((episode) => episode.title.trim() && episode.source.trim());
    if (firstEpisode) showVideo(firstEpisode, anime);
  };
  card.addEventListener("click", activate);
  card.addEventListener("keydown", (event) => {
    if (event.target.closest(".watched-remove")) return;
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      activate();
    }
  });
  return card;
};

const renderGallery = () => {
  const searchInput = document.getElementById("searchInput");
  const grid = document.getElementById("videoGrid");
  const emptyState = document.getElementById("emptyState");
  const query = searchInput.value.slice(0, 100).trim().toLocaleLowerCase("id");
  const filtered = readyVideos().filter((anime) => {
    const categoryMatch = viewingWatched || activeCategory === "Semua" || anime.category === activeCategory;
    const watchedMatch = !viewingWatched || watchedVideos.has(getWatchedKey(anime));
    const searchMatch = `${anime.title} ${anime.channel}`.toLocaleLowerCase("id").includes(query);
    return categoryMatch && watchedMatch && searchMatch;
  });
  const visibleVideos = viewingWatched || query ? filtered : filtered.slice(0, 14);
  grid.replaceChildren(...visibleVideos.map((anime) => createCard(anime)));
  emptyState.textContent = viewingWatched
    ? (visibleVideos.length ? "" : "Belum ada video yang ditonton.")
    : (readyVideos().length ? "Video tidak ditemukan." : "Belum ada video anime.");
  emptyState.hidden = visibleVideos.length > 0;
};

