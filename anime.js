const galleryView = document.getElementById("galleryView");
const watchView = document.getElementById("watchView");
const grid = document.getElementById("videoGrid");
const searchInput = document.getElementById("searchInput");
const searchForm = document.getElementById("searchForm");
const emptyState = document.getElementById("emptyState");
const watchVideo = document.getElementById("watchVideo");
const watchTitle = document.getElementById("watchTitle");
const watchMeta = document.getElementById("watchMeta");
const nextVideoList = document.getElementById("nextVideoList");
const sidebar = document.getElementById("sidebar");
const menuToggle = document.getElementById("menuToggle");
let activeCategory = "Semua";

const readyVideos = () => animeVideos.filter((anime) => anime.title.trim());

const renderEpisodes = (anime) => {
  const episodes = anime.episodes.filter((episode) => episode.title.trim() && episode.source.trim());
  nextVideoList.replaceChildren(...episodes.map((episode) => {
    const item = document.createElement("button");
    item.className = "next-video-item";
    item.type = "button";
    item.setAttribute("aria-label", `Putar ${anime.title} ${episode.title}`);

    const image = document.createElement("img");
    image.className = "next-video-preview";
    image.src = anime.poster;
    image.alt = "";
    const label = document.createElement("span");
    label.textContent = `${anime.title} · ${episode.title}`;
    item.append(image, label);
    item.addEventListener("click", () => showVideo(episode, anime));
    return item;
  }));
};

const showVideo = (episode, anime) => {
  galleryView.hidden = true;
  watchView.hidden = false;
  watchTitle.textContent = `${anime.title} — ${episode.title}`;
  watchMeta.textContent = `${anime.channel || "Anime"} · ${anime.category}`;
  watchVideo.pause();
  watchVideo.src = episode.source;
  if (anime.poster) watchVideo.poster = anime.poster;
  else watchVideo.removeAttribute("poster");
  watchVideo.load();
  watchVideo.play().catch(() => {});
  renderEpisodes(anime);
  window.scrollTo({ top: 0, behavior: "smooth" });
};

const createCard = (anime) => {
  const card = document.createElement("article");
  card.className = "video-card";
  card.tabIndex = 0;
  card.setAttribute("role", "button");
  const hasEpisodes = anime.episodes.some((episode) => episode.title.trim() && episode.source.trim());
  card.setAttribute("aria-label", hasEpisodes ? `Putar ${anime.title}` : `Slot thumbnail ${anime.title}, isi data anime di anime.js`);

  const thumbnail = document.createElement("div");
  thumbnail.className = "thumbnail-wrap";
  const image = document.createElement("img");
  if (anime.poster) image.src = anime.poster;
  else {
    thumbnail.classList.add("is-placeholder");
    const placeholder = document.createElement("span");
    placeholder.textContent = "Isi thumbnail";
    thumbnail.append(placeholder);
  }
  image.alt = "";
  image.loading = "lazy";
  image.decoding = "async";
  thumbnail.append(image);

  const info = document.createElement("div");
  info.className = "video-info";
  const avatar = document.createElement("span");
  avatar.className = "channel-avatar";
  avatar.setAttribute("aria-hidden", "true");
  avatar.textContent = "✦";
  const copy = document.createElement("div");
  copy.className = "video-copy";
  const title = document.createElement("h2");
  title.className = "video-title";
  title.textContent = anime.title;
  const meta = document.createElement("p");
  meta.className = "video-meta";
  meta.textContent = `${anime.channel || "Anime"} · ${anime.category}`;
  copy.append(title, meta);
  info.append(avatar, copy);
  card.append(thumbnail, info);

  const activate = () => {
    const firstEpisode = anime.episodes.find((episode) => episode.title.trim() && episode.source.trim());
    if (firstEpisode) showVideo(firstEpisode, anime);
  };
  card.addEventListener("click", activate);
  card.addEventListener("keydown", (event) => {
    if (event.key === "Enter" || event.key === " ") {
      event.preventDefault();
      activate();
    }
  });
  return card;
};

const renderGallery = () => {
  const query = searchInput.value.trim().toLocaleLowerCase("id");
  const filtered = readyVideos().filter((anime) => {
    const categoryMatch = activeCategory === "Semua" || anime.category === activeCategory;
    const searchMatch = `${anime.title} ${anime.channel}`.toLocaleLowerCase("id").includes(query);
    return categoryMatch && searchMatch;
  });
  grid.replaceChildren(...filtered.map((anime) => createCard(anime)));
  emptyState.textContent = readyVideos().length ? "Video tidak ditemukan." : "Belum ada video anime.";
  emptyState.hidden = filtered.length > 0;
};

document.querySelectorAll("[data-category]").forEach((chip) => {
  chip.addEventListener("click", () => {
    activeCategory = chip.dataset.category;
    document.querySelectorAll("[data-category]").forEach((item) => item.classList.toggle("active", item === chip));
    renderGallery();
  });
});

searchInput.addEventListener("input", renderGallery);
searchForm.addEventListener("submit", (event) => {
  event.preventDefault();
  renderGallery();
});
document.getElementById("backToGallery").addEventListener("click", () => {
  watchVideo.pause();
  watchView.hidden = true;
  galleryView.hidden = false;
  window.scrollTo({ top: 0, behavior: "smooth" });
});

menuToggle.addEventListener("click", () => {
  const isOpen = sidebar.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});
document.addEventListener("click", (event) => {
  if (window.matchMedia("(max-width: 760px)").matches && sidebar.classList.contains("open") &&
      !sidebar.contains(event.target) && !menuToggle.contains(event.target)) {
    sidebar.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  }
});

renderGallery();
